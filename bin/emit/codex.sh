# Codex emitter: adapters/codex/agents/<role>.toml and adapters/codex/config.toml.snippet. Sourced by build-adapters.sh.
CODEX_DIRS="adapters/codex"
emit_codex_begin() {
  mkdir -p "$OUT/adapters/codex/agents"
  CODEX_SNIPPET="$OUT/adapters/codex/config.toml.snippet"
  { echo "# Merge into .codex/config.toml (project) or ~/.codex/config.toml. Generated by bin/build-adapters.sh; do not edit."
    echo "# Role files live next to config.toml under agents/. Multi-agent must be enabled in your Codex version."
    echo
    echo "[agents]"
    echo "max_concurrent_threads_per_session = 3   # parallel subagents multiply token use; raise deliberately"; } > "$CODEX_SNIPPET"
}
emit_codex_role() {
  local sandbox=read-only xeffort xmodel
  [ "$RO" = 1 ] || sandbox=workspace-write
  eval "xeffort=\$CODEX_EFFORT_$T; xmodel=\$CODEX_MODEL_$T"
  if grep -q "'''" "$BODYFILE"; then echo "role $NAME contains ''' which breaks the TOML literal string" >&2; exit 1; fi
  { echo "# $NOTE"
    [ -z "$xmodel" ] || echo "model = \"$xmodel\""
    echo "model_reasoning_effort = \"$xeffort\""
    echo "sandbox_mode = \"$sandbox\""
    echo "developer_instructions = '''"
    echo "$PREAMBLE"
    cat "$BODYFILE"
    echo "'''"; } > "$OUT/adapters/codex/agents/$NAME.toml"
  { echo; echo "[agents.$NAME]"
    echo "description = \"$(printf '%s' "$DESC" | sed 's/\\/\\\\/g; s/"/\\"/g')\""
    echo "config_file = \"agents/$NAME.toml\""; } >> "$CODEX_SNIPPET"
}
